import { launch, newPage, waitReady, sleep, wheel, state, BASE } from './lib.mjs'
const browser = await launch()
const { page, ctx, log } = await newPage(browser)
await page.goto(BASE + '/'); await waitReady(page); await sleep(600); await page.mouse.move(800, 450)
const H = await page.evaluate(() => document.documentElement.scrollHeight - innerHeight)
await page.evaluate((y) => window.scrollTo(0, y), H); await sleep(300); await wheel(page, 100, 2); await sleep(2000)
console.log('no fim', (await state(page)).y)
await page.click('.ft-bottom__logo'); await sleep(4000)
console.log('depois do logo do footer', await state(page))
const r = await page.request.get(BASE + '/creditos.html'); console.log('creditos.html status', r.status(), (await r.text()).slice(0, 80).replace(/\s+/g, ' '))
// fontes: home direto vs home vinda do contato
const arch = () => page.evaluate(() => [...document.fonts].filter((f) => f.status === 'loaded' && /Archivo$|Playfair/.test(f.family.replace(/"/g, ''))).map((f) => `${f.family}:${f.stretch}:${f.weight}`).join(' | '))
console.log('home direto:', await arch())
const p2 = await ctx.newPage(); await p2.goto(BASE + '/contato'); await waitReady(p2); await sleep(800)
await p2.click('header .brand'); await sleep(1500); await waitReady(p2, 30000); await sleep(1500)
await p2.evaluate(() => window.scrollTo(0, 15500)); await sleep(300); await p2.mouse.wheel(0, 40); await sleep(2500)
console.log('home vinda do contato:', await p2.evaluate(() => [...document.fonts].filter((f) => f.status === 'loaded' && /Archivo$|Playfair/.test(f.family.replace(/"/g, ''))).map((f) => `${f.family}:${f.stretch}:${f.weight}`).join(' | ')))
await p2.screenshot({ path: 'fonts-from-contato.png' })
await page.evaluate(() => window.scrollTo(0, 15500)); await sleep(300); await page.mouse.wheel(0, 40); await sleep(2500)
await page.screenshot({ path: 'fonts-direct.png' })
console.log(log.slice(0, 5).join('\n'))
await ctx.close(); await browser.close()
